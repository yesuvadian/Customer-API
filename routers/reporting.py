# ── Helpers ────────────────────────────────────────────────────────────────

def _svc(db: Session, current_user: User,
         org_id: Optional[UUID] = None) -> ReportingService:
    """Resolve org from user's OrgUserRole if not supplied."""
    resolved = org_id
    if resolved is None:
        from models import OrgUserRole, OrgRole
        row = (
            db.query(OrgUserRole)
            .filter(OrgUserRole.user_id == current_user.id,
                    OrgUserRole.is_active.is_(True))
            .first()
        )
        if row:
            role = db.query(OrgRole).filter(OrgRole.id == row.org_role_id).first()
            if role:
                resolved = role.organization_id
    return ReportingService(db, org_id=resolved,
                            dept_ids=_user_dept_ids(db, current_user, resolved))


def _report_has_recipients(db: Session, defn, event: str, org_id) -> bool:
    """True when a report-ready notification for `defn` would reach someone:
    the definition's own Recipient Roles, or the event's email template roles
    (org override first, else the global default)."""
    if defn.recipient_roles:
        return True
    from models import NotificationTemplate
    tmpl = (
        db.query(NotificationTemplate)
        .filter(NotificationTemplate.event_type == event,
                NotificationTemplate.channel == "email",
                NotificationTemplate.is_active.is_(True),
                (NotificationTemplate.organization_id == org_id)
                | NotificationTemplate.organization_id.is_(None))
        .order_by(NotificationTemplate.organization_id.desc().nulls_last())
        .first()
    )
    return bool(tmpl and (tmpl.recipient_roles or tmpl.extra_recipient_emails))


def _email_report_to_user(db: Session, user: User, org_id, report_name: str,
                          files: list) -> None:
    """Email a just-generated report straight to `user`, file attached — for
    Run now on a report that has no recipients configured."""
    if not user.email:
        return
    from utils.email_service import EmailService
    from services.integration_settings_service import get_effective_smtp_config
    EmailService(get_effective_smtp_config(db, org_id)).send_multi_attachment_email_starttls_bcc(
        bcc_emails=[user.email],
        subject=f"[CogniWatt] Report Ready — {report_name}",
        body_html=(
            f"<h3 style='color:#1E3C72'>{report_name}</h3>"
            "<p>The report you ran is attached to this email. It is also "
            "available in SEACMS under Reporting Center &rarr; Log.</p>"
            "<p style='color:#888;font-size:12px'>Generated by CogniWatt SEACMS</p>"
        ),
        # files: [(raw, filename, content_type), ...] — both for "Both".
        attachments=[{"content": raw, "filename": fname,
                      "mime_type": (ctype or "application/octet-stream").split(";")[0]}
                     for raw, fname, ctype in files],
    )


def _user_dept_ids(db: Session, current_user: User, org_id) -> Optional[list]:
    """Department subtree a department-scoped user may see in reports, or
    None (no restriction) for org admins / users with no department — same
    scoping rule the dashboards use (utils.common_service)."""
    from utils.common_service import get_dept_subtree_ids, get_user_dept_scope
    is_org_admin, dept_id = get_user_dept_scope(db, current_user.id, org_id)
    if is_org_admin or not dept_id:
        return None
    return list(get_dept_subtree_ids(db, dept_id))


def _defn_to_dict(defn) -> dict:
    return {
        "id":               str(defn.id),
        "name":             defn.name,
        "description":      defn.description,
        "query_key":        defn.query_key,
        "parameters":       defn.parameters,
        "output_format":    defn.output_format,
        "frequency":        defn.frequency,
        "recipient_roles":  defn.recipient_roles,
        "is_active":        defn.is_active,
        "is_system":        defn.is_system,
        "last_generated_at": defn.last_generated_at.isoformat()
                              if defn.last_generated_at else None,
        "cts":              defn.cts.isoformat() if defn.cts else None,
    }


def _log_to_dict(log) -> dict:
    return {
        "id":             str(log.id),
        "definition_id":  str(log.definition_id),
        "output_format":  log.output_format,
        "file_name":      log.file_name,
        "file_size":      log.file_size,
        "row_count":      log.row_count,
        "status":         log.status,
        "error_message":  log.error_message,
        "started_at":     log.started_at.isoformat()   if log.started_at   else None,
        "completed_at":   log.completed_at.isoformat() if log.completed_at else None,
        "cts":            log.cts.isoformat()           if log.cts          else None,
    }


# ── Pydantic schemas ───────────────────────────────────────────────────────

class DefinitionCreate(BaseModel):
    name:            str
    description:     Optional[str] = None
    query_key:       str
    parameters:      dict = {}
    output_format:   str  = "excel"
    frequency:       str  = "on_demand"
    recipient_roles: list = []


class DefinitionUpdate(BaseModel):
    name:            Optional[str]  = None
    description:     Optional[str]  = None
    parameters:      Optional[dict] = None
    output_format:   Optional[str]  = None
    frequency:       Optional[str]  = None
    recipient_roles: Optional[list] = None
    is_active:       Optional[bool] = None


class RunRequest(BaseModel):
    parameters:    dict = {}
    output_format: str  = "excel"   # excel | pdf


class ConsolidatedReportRequest(BaseModel):
    department_id:     UUID
    equipment_type_id: int
    test_type_ids:     list[int] = []
    date_from:         Optional[str] = None   # "YYYY-MM-DD"
    date_to:           Optional[str] = None
    equipment_ids:     Optional[list[UUID]] = None
    delivery:          str = "on_demand"      # on_demand | email
    output_format:     str = "pdf"            # on_demand: pdf | excel  (email always sends both)


