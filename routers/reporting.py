@router.get("/definitions/query-keys")
def get_query_keys(
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """Return available report query keys from the database."""
    keys = (
        db.query(ReportQueryKey)
        .filter(ReportQueryKey.is_active.is_(True))
        .order_by(ReportQueryKey.group_name, ReportQueryKey.sort_order)
        .all()
    )
    return [
        {
            "key":               k.key,
            "label":             k.label,
            "description":       k.description,
            "group_name":        k.group_name,
            "parameters_schema": k.parameters_schema,
        }
        for k in keys
    ]


@router.get("/definitions")
def list_definitions(
    active_only: bool = Query(True),
    org_id: Optional[UUID] = Query(None),
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    svc   = _svc(db, current_user, org_id)
    defs  = svc.list_definitions(active_only=active_only)
    return [_defn_to_dict(d) for d in defs]


@router.post("/definitions", status_code=201)
def create_definition(
    body: DefinitionCreate,
    org_id: Optional[UUID] = Query(None),
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    svc  = _svc(db, current_user, org_id)
    defn = svc.create_definition(body.dict(), user_id=current_user.id)
    return _defn_to_dict(defn)


@router.get("/definitions/{definition_id}")
def get_definition(
    definition_id: UUID,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    svc  = _svc(db, current_user)
    defn = svc.get_definition(definition_id)
    if not defn:
        raise HTTPException(404, "Report definition not found")
    return _defn_to_dict(defn)


@router.put("/definitions/{definition_id}")
def update_definition(
    definition_id: UUID,
    body: DefinitionUpdate,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    svc = _svc(db, current_user)
    try:
        defn = svc.update_definition(
            definition_id,
            {k: v for k, v in body.dict().items() if v is not None},
            user_id=current_user.id,
        )
    except ValueError as e:
        raise HTTPException(404, str(e))
    return _defn_to_dict(defn)


@router.delete("/definitions/{definition_id}", status_code=204)
def delete_definition(
    definition_id: UUID,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    svc = _svc(db, current_user)
    try:
        svc.delete_definition(definition_id, user_id=current_user.id)
    except ValueError:
        raise HTTPException(404, "Report definition not found")
    except PermissionError as e:
        raise HTTPException(403, str(e))
    return Response(status_code=204)


@router.post("/definitions/{definition_id}/run")
def run_report(
    definition_id: UUID,
    body: RunRequest,
    org_id: Optional[UUID] = Query(None),
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """
    Generate report and return the file as binary.
    Content-Disposition header carries the filename.
    """
    svc = _svc(db, current_user, org_id)
    # "both" = one Excel + one PDF from the same run, emailed together in ONE
    # email (two separate runs sent two same-subject emails that mail clients
    # thread together, so only the newer file showed). The response is then
    # JSON listing both files; the app downloads each via /reports/download.
    formats = ["excel", "pdf"] if body.output_format == "both" else [body.output_format]
    generated = []   # (raw, filename, content_type)
    try:
        for fmt in formats:
            generated.append(svc.generate(
                definition_id=definition_id,
                parameters=body.parameters,
                output_format=fmt,
                user_id=current_user.id,
            ))
    except ValueError as e:
        # Only a missing definition is a 404 — anything else (a report that
        # can't be department-scoped, a value the renderer rejects) was
        # surfacing as a misleading "404" too.
        msg = str(e)
        raise HTTPException(404 if "not found" in msg.lower() else 422, msg)
    except RuntimeError as e:
        raise HTTPException(422, str(e))
    raw, filename, content_type = generated[0]
    extra_files = [g[1] for g in generated[1:]]

    # Run now always emails the report, same as a scheduled run:
    #   • definition has recipients (its Recipient Roles, or its event
    #     template's roles) → the same "report ready" notification the
    #     scheduled job fires, file(s) attached;
    #   • no recipients anywhere → emailed straight to whoever clicked Run.
    # A definition with no event of its own (on-demand ones) uses the
    # generic scheduled_report_ready event.
    try:
        from models import ReportDefinition
        from services.reporting_service import fire_report_ready
        defn = db.query(ReportDefinition).filter(ReportDefinition.id == definition_id).first()
        if defn:
            event = defn.notification_event or "scheduled_report_ready"
            if _report_has_recipients(db, defn, event, svc.org_id):
                if svc.dept_ids:
                    # Department-only report → notify only this org + department.
                    from utils.common_service import get_user_dept_scope
                    _, _dept = get_user_dept_scope(db, current_user.id, svc.org_id)
                    fire_report_ready(db, defn, filename, organization_id=svc.org_id,
                                      department_id=_dept, event_type=event,
                                      extra_filenames=extra_files)
                else:
                    fire_report_ready(db, defn, filename, event_type=event,
                                      extra_filenames=extra_files)
            else:
                _email_report_to_user(db, current_user, svc.org_id, defn.name, generated)
    except Exception as notif_exc:
        print(f"[Reports] Notification for definition {definition_id} failed: {notif_exc}")

    if len(generated) > 1:
        return {"files": [{"filename": g[1], "content_type": g[2]} for g in generated]}

    return Response(
        content=raw,
        media_type=content_type,
        headers={
            "Content-Disposition": f'attachment; filename="{filename}"',
            "X-Report-Filename":   filename,
            "X-Row-Count":         str(len(raw)),   # approximate
        },
    )


